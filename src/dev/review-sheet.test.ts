// Writes the human review worksheets to docs/review/<track>.md:
// every template family at a low, middle and high level, with the prompt, rule,
// hints, the board, each wrong answer's misconception tag, the checker's answer,
// and the explanation, plus the sign-off checklist.
// npm run content:worksheet
import { it } from 'vitest';
import { correctAnswerText, generateItem, SKILL_BY_ID, TEMPLATES, TRACKS, type Item } from '../content';
import { optionIsCorrect } from '../content/check';
import { fmt } from '../content/format';
import { SIGNOFFS } from '../content/signoff';

const SEED = 20261102;

export const reviewLevels = (minLevel = 1): number[] => [...new Set([minLevel, Math.round((minLevel + 10) / 2), 10])];

function board(item: Item): string[] {
  const p = item.payload;
  switch (p.kind) {
    case 'sort':
      return [`Sort into "${p.yesLabel}" / "${p.noLabel}": ${p.numbers.map((n) => fmt(n)).join(', ')}`];
    case 'construct':
      return [`Build: ${p.fixed.map((d) => (d === null ? '_' : d)).join('')} (${p.mode === 'all' ? 'pick every digit that works' : 'fill the blanks'})`];
    case 'refute':
      return [`Claim: ${p.claimText}`, `Candidates: ${p.candidates.map((c) => c.map((v, i) => `${p.varNames[i]} = ${fmt(v)}`).join(', ')).join(' | ')}`];
    case 'choice':
      return p.options.map((o) => `${optionIsCorrect(p, o) ? '**[correct]**' : '[wrong]'} ${o.label}${o.misconception ? ` (misconception: \`${o.misconception}\`)` : optionIsCorrect(p, o) ? '' : ' (no misconception tag)'}`);
    case 'numeric':
      return [`Type a whole number${p.unit ? ` (${p.unit})` : ''}`];
  }
}

function itemBlock(item: Item): string {
  const lines = [
    `#### Level ${item.level} \`${item.id}\``,
    '',
    `**Prompt.** ${item.prompt}`,
    '',
    ...(item.ruleLens ? [`**Rule.** ${item.ruleLens}`, ''] : []),
    ...board(item).map((b) => `- ${b}`),
    '',
    `**Answer (from the checker).** ${item.payload.kind === 'sort' ? correctAnswerText(item).split(', ').filter(Boolean).map((n) => fmt(n)).join(', ') || 'none' : correctAnswerText(item)}`,
    '',
    ...(item.hints.length ? ['**Hints.**', ...item.hints.map((h, i) => `${i + 1}. ${h}`), ''] : []),
    `**Explanation.** ${item.explanation}`,
    '',
  ];
  return lines.join('\n');
}

// The app's tsconfig has no Node types (they clash with React Native's), so the two file calls are typed here.
type Fs = { mkdirSync(p: string, o: { recursive: boolean }): void; writeFileSync(p: string, data: string): void };

it('write review worksheets', async () => {
  const { mkdirSync, writeFileSync }: Fs = await import('node:fs' as string);
  const dir = `${(process as unknown as { cwd(): string }).cwd()}/docs/review`;
  mkdirSync(dir, { recursive: true });
  for (const track of TRACKS.filter((t) => t.available)) {
    const families = TEMPLATES.filter((t) => SKILL_BY_ID[t.skillId]?.track === track.id);
    const parts = [
      `# ${track.name}: review worksheet`,
      '',
      `Generated by \`npm run content:worksheet\` (seed ${SEED}). ${families.length} families. Each is shown at a low, middle and high level.`,
      'Read docs/review/README.md first. Record each sign-off in `src/content/signoff.ts`.',
      '',
    ];
    for (const t of families) {
      const signed = SIGNOFFS[t.id];
      parts.push(
        `## \`${t.id}\` v${t.version}`,
        '',
        `${SKILL_BY_ID[t.skillId]?.name ?? t.skillId}. Board: ${t.board}${t.transfer ? '. Transfer family' : ''}.${signed ? ` Signed off v${signed.version} by ${signed.reviewer} on ${signed.date}.` : ''}`,
        '',
      );
      for (const level of reviewLevels(t.minLevel)) parts.push(itemBlock(generateItem(t.id, level, SEED + level, { allowDisabled: true })));
      parts.push(
        '**Checklist** (all three levels)',
        '',
        '- [ ] Wording is clear, and there is only one reasonable reading',
        '- [ ] Hints help in order, and none gives the answer away',
        '- [ ] Each wrong answer is a mistake a real learner makes, and its misconception tag names that mistake',
        '- [ ] The explanation is correct and talks about this puzzle, not the topic in general',
        '- [ ] Difficulty rises from low to high, and the high level is fair',
        '- [ ] Nothing depends on color alone, dragging, or reading speed',
        '',
        'Verdict: Approve / Fix (say what) / Retire. Reviewer: ______ Date: ______',
        '',
        '---',
        '',
      );
    }
    writeFileSync(`${dir}/${track.id}.md`, parts.join('\n'));
  }
});
